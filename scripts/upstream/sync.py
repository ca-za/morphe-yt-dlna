#!/usr/bin/env python3
"""
Brings our app versions in line with the official Morphe patches.

Morphe Manager patches our bundle together with the official one only for an app version both
list, so ours lists the same versions. A version is recommended (not experimental) only when
Morphe recommends it AND it passed our emulator test (tests/regression/verified.json, written
by tests/regression/run.py). Every other version is experimental.

  scripts/upstream/sync.py --official patches-list.json --patches 2.0.0 --desktop 1.20.0

--official: the official patches-list.json (of the release tag). Without it, the one recorded
in scripts/upstream/state.json is fetched from GitHub (needs gh), so a local run after a
regression test only promotes the versions that passed.

Writes Constants.kt and state.json; prints the versions that are new to our list as JSON
({"package": ["version", ...]}), the ones to patch-test.
"""

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CONSTANTS = ROOT / "patches/src/main/kotlin/app/ytdlna/patches/shared/Constants.kt"
STATE = ROOT / "scripts/upstream/state.json"
VERIFIED = ROOT / "tests/regression/verified.json"
OFFICIAL_REPO = "MorpheApp/morphe-patches"

# Package -> name of its Compatibility in Constants.kt.
PACKAGES = {
    "com.google.android.youtube": "COMPATIBILITY_YOUTUBE",
    "com.google.android.apps.youtube.music": "COMPATIBILITY_YOUTUBE_MUSIC",
}

BEGIN = "// region targets (generated by scripts/upstream/sync.py, edit verified.json instead)"
END = "// endregion"


def official_targets(patches_list: dict, package: str) -> list[dict]:
    """
    The versions the most official patches of {package} support, newest first: like
    list-versions, a version only a few patches list (an older or a newer one) is left out.
    """
    count: dict[str, int] = {}
    target: dict[str, dict] = {}
    for patch in patches_list["patches"]:
        for compat in patch.get("compatiblePackages") or []:
            if compat.get("packageName") != package:
                continue
            for t in compat.get("targets") or []:
                count[t["version"]] = count.get(t["version"], 0) + 1
                target.setdefault(t["version"], t)
    if not count:
        raise SystemExit(f"No official targets for {package}")
    most = max(count.values())
    versions = [v for v, n in count.items() if n == most]
    versions.sort(key=lambda v: [int(p) if p.isdigit() else 0 for p in re.split(r"[.-]", v)], reverse=True)
    return [target[v] for v in versions]


def current_versions(text: str, name: str) -> list[str]:
    block = compat_block(text, name)
    return re.findall(r'AppTarget\(version = "([^"]+)"', block)


def compat_block(text: str, name: str) -> str:
    start = text.index(f"val {name} = Compatibility(")
    end = text.index("\n    )\n", start)
    return text[start:end]


def render(targets: list[dict], verified: set[str]) -> list[str]:
    lines = []
    for t in targets:
        recommended = not t.get("isExperimental") and t["version"] in verified
        comment = ""
        if not t.get("isExperimental") and not recommended:
            comment = "  // Recommended by Morphe, our emulator test pending."
        lines.append(f'AppTarget(version = "{t["version"]}", minSdk = {t.get("minSdk") or 26}'
                     + ("" if recommended else ", isExperimental = true") + f"),{comment}")
    return lines


def replace_targets(text: str, name: str, lines: list[str]) -> str:
    start = text.index(f"val {name} = Compatibility(")
    open_ = text.index("targets = listOf(\n", start) + len("targets = listOf(\n")
    close = text.index("\n        )\n", open_)
    indent = " " * 12
    body = "\n".join([indent + BEGIN] + [indent + l for l in lines] + [indent + END])
    return text[:open_] + body + text[close:]


def fetch_official(version: str) -> dict:
    raw = subprocess.run(
        ["gh", "api", f"repos/{OFFICIAL_REPO}/contents/patches-list.json?ref=v{version}",
         "-H", "Accept: application/vnd.github.raw"],
        capture_output=True, text=True, check=True).stdout
    return json.loads(raw)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--official", type=Path, help="official patches-list.json")
    parser.add_argument("--patches", help="official patches version (default: as in state.json)")
    parser.add_argument("--desktop", help="Morphe Desktop version (default: as in state.json)")
    args = parser.parse_args()

    state = json.loads(STATE.read_text())
    if args.patches:
        state["morphePatches"] = args.patches
    if args.desktop:
        state["morpheDesktop"] = args.desktop
    official = json.loads(args.official.read_text()) if args.official else fetch_official(state["morphePatches"])
    verified = json.loads(VERIFIED.read_text()) if VERIFIED.exists() else {}

    text = CONSTANTS.read_text()
    new: dict[str, list[str]] = {}
    for package, name in PACKAGES.items():
        targets = official_targets(official, package)
        before = set(current_versions(text, name))
        new[package] = [t["version"] for t in targets if t["version"] not in before]
        text = replace_targets(text, name, render(targets, set(verified.get(package, []))))
    CONSTANTS.write_text(text)
    STATE.write_text(json.dumps(state, indent=2) + "\n")
    json.dump(new, sys.stdout)
    print()


if __name__ == "__main__":
    main()
